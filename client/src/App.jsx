import { useState, useEffect, useRef } from "react";
import { sendChatMessage } from "./services/chatService";
import "./App.css";
import Message from "./components/Message";
import Welcome from "./components/Welcome";
import ChatInput from "./components/ChatInput";

function App() {
  const [question, setQuestion] = useState("");
  const [messages, setMessages] = useState([]);
  const [loading, setLoading] = useState(false);
  const chatEndRef = useRef(null);

  useEffect(() => {
    chatEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, loading]);

  async function handleSubmit(event) {
    event.preventDefault();

    const trimmedQuestion = question.trim();

    if (!trimmedQuestion || loading) return;

    setMessages((previous) => [
      ...previous,
      { role: "user", content: trimmedQuestion },
    ]);

    setQuestion("");
    setLoading(true);

    try {
      const data = await sendChatMessage(trimmedQuestion);

      setMessages((previous) => [
        ...previous,
        {
          role: "assistant",
          content: data.answer,
          sources: data.sources,
        },
      ]);
    } catch (error) {
      setMessages((previous) => [
        ...previous,
        {
          role: "assistant",
          content: `Error: ${error.message}`,
          failedQuestion: trimmedQuestion,
          sources: [],
        },
      ]);
    } finally {
      setLoading(false);
    }
  }
  return (
    <main className="app">
      <header className="header">
        <div className="logo">R</div>
        <div>
          <h1>Resume Assistant</h1>
          <p>Ask questions about Asheesh's experience and projects</p>
        </div>
      </header>

      <section className="chat">
        {messages.length === 0 && (
          <Welcome onSelect={setQuestion} />
        )}
        {messages.map((message, index) => (
          <Message
            key={`${message.role}-${index}`}
            message={message}
            onRetry={(failedQuestion) => setQuestion(failedQuestion)}
          />
        ))}

        {loading && (
          <div className="loading">
            <span className="spinner" />
            Searching the resume and generating an answer...
          </div>
        )}
        <div ref={chatEndRef} />
      </section>

      <ChatInput
        question={question}
        onQuestionChange={setQuestion}
        onSubmit={handleSubmit}
        loading={loading}
      />

      <footer>
        Answers are generated by AI and should be verified against the sources.
      </footer>
    </main>
  );
}

export default App;